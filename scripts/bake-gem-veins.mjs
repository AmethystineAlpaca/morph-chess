import * as THREE from 'three';
import { writeFile } from 'node:fs/promises';
import { rubySet } from '../pieces/ruby/index.js';
import { veinAtlasKey, veinAtlasLayout, VEIN_TILE, VEIN_PADDING } from '../pieces/ruby/vein-atlas.js';

// Geometry/material factories need only this off-screen studio interface to
// author the meshes. No browser, GPU or canvas rasterizer is used for baking.
globalThis.document = { createElement: () => ({ getContext: () => ({ createRadialGradient: () => ({ addColorStop() {} }), fillRect() {} }) }) };
const renderer = { coordinateSystem: THREE.WebGLCoordinateSystem, xr: { enabled: false }, getRenderTarget() { return null; }, getActiveCubeFace() { return 0; }, getActiveMipmapLevel() { return 0; }, setRenderTarget() {}, render() {} };

function encode(pixels) {
  const bytes = [];
  let offset = 0;
  while (offset < pixels.length) {
    let skip = 0;
    while (offset < pixels.length && pixels[offset] === 0 && skip < 65535) { offset++; skip++; }
    const start = offset;
    while (offset < pixels.length && pixels[offset] !== 0 && offset - start < 65535) offset++;
    const count = offset - start;
    bytes.push(skip & 255, skip >> 8, count & 255, count >> 8);
    for (let i = start; i < offset; i++) bytes.push(pixels[i]);
  }
  return Buffer.from(bytes).toString('base64');
}

function bake(geometry, veins) {
  const { faces, columns, width, height } = veinAtlasLayout(geometry);
  const pixels = new Uint8Array(width * height);
  const position = geometry.attributes.position;
  const segments = veins.segments.map(([a, b]) => [new THREE.Vector3(...a), new THREE.Vector3(...b)]);
  const point = new THREE.Vector3(), normal = new THREE.Vector3(), axis = new THREE.Vector3(), w = new THREE.Vector3(), closest = new THREE.Vector3();
  const span = VEIN_TILE - VEIN_PADDING * 2 - 1;
  for (let face = 0; face < faces; face++) {
    const [a, b, c] = [0, 1, 2].map(i => new THREE.Vector3().fromBufferAttribute(position, face * 3 + i));
    normal.copy(b).sub(a).cross(c.clone().sub(a)).normalize().negate();
    const aa = Math.max(veins.width, Math.max(a.distanceTo(b), a.distanceTo(c)) / span * .30);
    for (let y = 0; y < VEIN_TILE; y++) for (let x = 0; x < VEIN_TILE; x++) {
      const u = (x - VEIN_PADDING) / span, v = (y - VEIN_PADDING) / span;
      point.copy(a).multiplyScalar(1 - u - v).addScaledVector(b, u).addScaledVector(c, v);
      let mask = 0;
      for (const [start, end] of segments) {
        axis.copy(end).sub(start); w.copy(point).sub(start);
        const bn = normal.dot(axis), cn = axis.lengthSq(), dn = normal.dot(w), en = axis.dot(w);
        let along = Math.max(0, (bn * en - cn * dn) / Math.max(1e-9, cn - bn * bn));
        let t = THREE.MathUtils.clamp((bn * along + en) / cn, 0, 1);
        along = Math.max(0, closest.copy(start).addScaledVector(axis, t).sub(point).dot(normal));
        t = THREE.MathUtils.clamp((bn * along + en) / cn, 0, 1);
        closest.copy(w).addScaledVector(normal, along).addScaledVector(axis, -t);
        // Fixed mineral inclusion: preserve the 100% path shape, taper its edges
        // and recess deeper branches. No time, emission or scene lighting.
        const stroke = Math.exp(-closest.lengthSq() / (aa * aa)) * Math.exp(-along * 1.6);
        mask = Math.max(mask, stroke);
      }
      pixels[(Math.floor(face / columns) * VEIN_TILE + y) * width + (face % columns) * VEIN_TILE + x] = Math.round(mask * 255);
    }
  }
  return encode(pixels);
}

const baked = {};
for (const type of rubySet.availablePieces) {
  const model = rubySet.create(type, renderer, { bakedVeins: false });
  model.traverse(mesh => {
    const veins = mesh.material?.userData.veins;
    if (!veins?.segments.length) return;
    const key = veinAtlasKey(mesh.geometry, veins);
    if (!baked[key]) baked[key] = bake(mesh.geometry, veins);
  });
}
await writeFile(new URL('../pieces/ruby/baked-veins.js', import.meta.url), `// Generated by npm run bake:veins. Static model material masks.\nexport const BAKED_VEINS = ${JSON.stringify(baked)};\n`);
console.log(`Baked ${Object.keys(baked).length} head material masks (${Math.round(JSON.stringify(baked).length / 1024)} KiB).`);
